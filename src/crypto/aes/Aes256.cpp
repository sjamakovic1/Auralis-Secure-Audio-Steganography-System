constexpr std::array<std::uint8_t, 8> Rcon{0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40};

std::uint8_t value(std::byte byte) noexcept
{
    return std::to_integer<std::uint8_t>(byte);
}

std::byte substitute(std::byte byte, const std::array<std::uint8_t, 256>& box) noexcept
{
    return static_cast<std::byte>(box[value(byte)]);
}

void subBytes(Block& state) noexcept
{
    for (auto& byte : state) byte = substitute(byte, SBox);
}

void inverseSubBytes(Block& state) noexcept
{
    for (auto& byte : state) byte = substitute(byte, InverseSBox);
}

void shiftRows(Block& state) noexcept
{
    const Block original = state;
    for (std::size_t row = 1; row < 4; ++row) {
        for (std::size_t column = 0; column < 4; ++column) {
            state[4U * column + row] = original[4U * ((column + row) % 4U) + row];
        }
    }
}

void inverseShiftRows(Block& state) noexcept
{
    const Block original = state;
    for (std::size_t row = 1; row < 4; ++row) {
        for (std::size_t column = 0; column < 4; ++column) {
            state[4U * column + row] = original[4U * ((column + 4U - row) % 4U) + row];
        }
    }
}

std::uint8_t gfMultiply(std::uint8_t left, std::uint8_t right) noexcept
{
    std::uint8_t result = 0;
    for (std::size_t bit = 0; bit < 8; ++bit) {
        if ((right & 1U) != 0) result ^= left;
        const bool highBit = (left & 0x80U) != 0;
        left = static_cast<std::uint8_t>(left << 1U);
        if (highBit) left ^= 0x1bU;
        right = static_cast<std::uint8_t>(right >> 1U);
    }
    return result;
}

void mixColumns(Block& state) noexcept
{
    for (std::size_t column = 0; column < 4; ++column) {
        const std::size_t i = 4U * column;
        const std::uint8_t a0 = value(state[i]);
        const std::uint8_t a1 = value(state[i + 1U]);
        const std::uint8_t a2 = value(state[i + 2U]);
        const std::uint8_t a3 = value(state[i + 3U]);
        state[i] = static_cast<std::byte>(gfMultiply(0x02, a0) ^ gfMultiply(0x03, a1) ^ a2 ^ a3);
        state[i + 1U] = static_cast<std::byte>(a0 ^ gfMultiply(0x02, a1) ^ gfMultiply(0x03, a2) ^ a3);
        state[i + 2U] = static_cast<std::byte>(a0 ^ a1 ^ gfMultiply(0x02, a2) ^ gfMultiply(0x03, a3));
        state[i + 3U] = static_cast<std::byte>(gfMultiply(0x03, a0) ^ a1 ^ a2 ^ gfMultiply(0x02, a3));
    }
}

void inverseMixColumns(Block& state) noexcept
{
    for (std::size_t column = 0; column < 4; ++column) {
        const std::size_t i = 4U * column;
        const std::uint8_t a0 = value(state[i]);
        const std::uint8_t a1 = value(state[i + 1U]);
        const std::uint8_t a2 = value(state[i + 2U]);
        const std::uint8_t a3 = value(state[i + 3U]);
        state[i] = static_cast<std::byte>(gfMultiply(0x0e, a0) ^ gfMultiply(0x0b, a1) ^ gfMultiply(0x0d, a2) ^ gfMultiply(0x09, a3));
        state[i + 1U] = static_cast<std::byte>(gfMultiply(0x09, a0) ^ gfMultiply(0x0e, a1) ^ gfMultiply(0x0b, a2) ^ gfMultiply(0x0d, a3));
        state[i + 2U] = static_cast<std::byte>(gfMultiply(0x0d, a0) ^ gfMultiply(0x09, a1) ^ gfMultiply(0x0e, a2) ^ gfMultiply(0x0b, a3));
        state[i + 3U] = static_cast<std::byte>(gfMultiply(0x0b, a0) ^ gfMultiply(0x0d, a1) ^ gfMultiply(0x09, a2) ^ gfMultiply(0x0e, a3));
    }
}

void addRoundKey(Block& state, const Block& roundKey) noexcept
{
    for (std::size_t i = 0; i < state.size(); ++i) state[i] ^= roundKey[i];
}

Word rotateWord(const Word& word) noexcept
{
    return {word[1], word[2], word[3], word[0]};
}

Word subWord(Word word) noexcept
{
    for (auto& byte : word) byte = substitute(byte, SBox);
    return word;
}

