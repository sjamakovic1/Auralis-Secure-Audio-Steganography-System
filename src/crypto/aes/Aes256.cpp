Aes256::Aes256(const Key& key)
{
    constexpr std::size_t keyWords = 8;
    constexpr std::size_t totalWords = 4U * (Rounds + 1U);
    std::array<Word, totalWords> words{};

    for (std::size_t i = 0; i < keyWords; ++i) {
        for (std::size_t byte = 0; byte < 4; ++byte) words[i][byte] = key[4U * i + byte];
    }

    for (std::size_t i = keyWords; i < totalWords; ++i) {
        Word temporary = words[i - 1U];
        if (i % keyWords == 0) {
            temporary = subWord(rotateWord(temporary));
            temporary[0] ^= static_cast<std::byte>(Rcon[i / keyWords]);
        } else if (i % keyWords == 4U) {
            temporary = subWord(temporary);
        }
        for (std::size_t byte = 0; byte < 4; ++byte) {
            words[i][byte] = words[i - keyWords][byte] ^ temporary[byte];
        }
    }

    for (std::size_t round = 0; round <= Rounds; ++round) {
        for (std::size_t column = 0; column < 4; ++column) {
            for (std::size_t row = 0; row < 4; ++row) {
                roundKeys_[round][4U * column + row] = words[4U * round + column][row];
            }
        }
    }
}

Aes256::Block Aes256::encryptBlock(const Block& plaintext) const
{
    Block state = plaintext;
    addRoundKey(state, roundKeys_[0]);
    for (std::size_t round = 1; round < Rounds; ++round) {
        subBytes(state);
        shiftRows(state);
        mixColumns(state);
        addRoundKey(state, roundKeys_[round]);
    }
    subBytes(state);
    shiftRows(state);
    addRoundKey(state, roundKeys_[Rounds]);
    return state;
}

Aes256::Block Aes256::decryptBlock(const Block& ciphertext) const
{
    Block state = ciphertext;
    addRoundKey(state, roundKeys_[Rounds]);
    for (std::size_t round = Rounds - 1U; round > 0; --round) {
        inverseShiftRows(state);
        inverseSubBytes(state);
        addRoundKey(state, roundKeys_[round]);
        inverseMixColumns(state);
    }
    inverseShiftRows(state);
    inverseSubBytes(state);
    addRoundKey(state, roundKeys_[0]);
    return state;
}

